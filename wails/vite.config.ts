import { defineConfig, type UserConfig, type Plugin } from 'vite'
import react, { reactCompilerPreset } from '@vitejs/plugin-react'
import babel from '@rolldown/plugin-babel'
import tailwindcss from '@tailwindcss/vite'
import fs from 'node:fs'
import path, { resolve } from 'path'
import { fileURLToPath } from 'url'
import packageJson from '../package.json'

// Wails spike frontend build: reuses the main repo's Vite + React + Tailwind
// toolchain and the entire src/ component tree. All `@tauri-apps/*` imports
// are aliased to Wails shims that route `invoke` through the bindings
// generated by `wails3 generate bindings -ts` into wails/frontend/bindings.

const dir = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(dir, '..')

const shim = (name: string) => resolve(dir, '../src/wails/shims', name)

/**
 * `emptyOutDir` wipes frontend/dist on every build, including the tracked
 * `.gitkeep` that keeps `//go:embed all:frontend/dist` compiling on a clean
 * clone (wails/.gitignore negation). Restore it after each build so
 * `git status` stays clean.
 */
function restoreGitkeep(): Plugin {
  return {
    name: 'restore-frontend-dist-gitkeep',
    closeBundle() {
      fs.writeFileSync(resolve(dir, 'frontend/dist/.gitkeep'), '')
    },
  }
}

export default defineConfig(async () => {
  const babelPlugin = await babel({ presets: [reactCompilerPreset()] })
  return {
    root: dir,
    publicDir: resolve(repoRoot, 'public'),
    define: {
      __APP_VERSION__: JSON.stringify(packageJson.version),
      // Gates src/lib/capabilities.ts: the shared components render tools
      // whose Go backend does not exist yet as disabled placeholders.
      __WAILS_BACKEND__: 'true',
    },
    plugins: [react(), babelPlugin, tailwindcss(), restoreGitkeep()],
    resolve: {
      alias: {
        '@': resolve(repoRoot, 'src'),
        '@wails-bindings': resolve(
          dir,
          'frontend/bindings/droidgear-wails/internal/app/app.ts'
        ),
        '@tauri-apps/api/core': shim('tauri-core.ts'),
        '@tauri-apps/api/event': shim('tauri-event.ts'),
        '@tauri-apps/api/webviewWindow': shim('tauri-webview-window.ts'),
        '@tauri-apps/api/window': shim('tauri-webview-window.ts'),
        '@tauri-apps/plugin-opener': shim('tauri-opener.ts'),
        'tauri-plugin-system-fonts-api': shim('tauri-system-fonts.ts'),
        '@tauri-apps/plugin-os': shim('tauri-os.ts'),
        '@tauri-apps/plugin-dialog': shim('tauri-dialog.ts'),
        '@tauri-apps/plugin-fs': shim('tauri-fs.ts'),
        '@tauri-apps/plugin-clipboard-manager': shim(
          'tauri-clipboard-manager.ts'
        ),
        // Go PTY service behind the tauri-pty API (see shims/tauri-pty.ts);
        // the npm package's Rust plugin does not exist in the Wails build.
        'tauri-pty': shim('tauri-pty.ts'),
      },
    },
    server: {
      host: '127.0.0.1',
      port: Number(process.env.WAILS_VITE_PORT) || 9245,
      strictPort: true,
      fs: {
        allow: [repoRoot],
      },
    },
    build: {
      chunkSizeWarningLimit: 600,
      cssMinify: 'lightningcss',
      outDir: resolve(dir, 'frontend/dist'),
      emptyOutDir: true,
      rollupOptions: {
        input: resolve(dir, 'index.html'),
      },
    },
    clearScreen: false,
  } satisfies UserConfig
})
